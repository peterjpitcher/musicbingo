/**
 * The reviewed allowlist of database objects the `anon` role can reach.
 *
 * WHAT THIS IS
 *   A committed record of exactly what Supabase's public anon key can touch in
 *   the `public` schema of project ihyazjaklyhacxixhwww, as reviewed by a human.
 *   `scripts/check-anon-access.mjs` reads the live catalogue and fails when the
 *   database grants anon anything this file does not list, or grants more on a
 *   listed object than this file allows.
 *
 * THE REVIEWED STATE IS: NOTHING
 *   The allowlist below is empty, deliberately. Read live on 5 September 2026,
 *   the `public` schema holds four tables (brands, live_sessions, session_events,
 *   session_runtime_snapshots), one function (prune_session_events), no views and
 *   no sequences, and anon holds no privilege on any of them. Their ACLs name
 *   only postgres and service_role. Row level security is on for all four tables.
 *
 * WHY EMPTY IS THE RIGHT ANSWER HERE, NOT JUST THE CURRENT ONE
 *   This app never uses the anon key. `lib/supabase.ts` is the only file that
 *   builds a Supabase client and it requires SUPABASE_URL plus
 *   SUPABASE_SERVICE_ROLE_KEY, server side. There is no publishable key in
 *   `.env.example`, in the code, or in any browser bundle. Nothing the app does
 *   needs anon to reach anything, so any appearance of anon reach is drift by
 *   definition and not a feature. That is why this file starts empty and the
 *   check fails the moment a single object shows up.
 *
 * WHY THE GUARD EXISTS AT ALL
 *   Across this workspace the publishable key repeatedly reached further than
 *   anyone intended, because Supabase's default privileges grant anon every
 *   privilege on each new table and EXECUTE on each new function. Grants were
 *   clawed back object by object and the next migration re-armed them.
 *
 *   That root cause was closed here earlier than in the sibling projects, for
 *   tables and sequences. Migration 20260808170000_drop_dead_tables_and_harden
 *   ran ALTER DEFAULT PRIVILEGES ... REVOKE ALL ... FROM anon, authenticated on
 *   tables, sequences and functions. The live catalogue agrees: the
 *   `pg_default_acl` rows whose grantor is `postgres`, which is the role
 *   migrations run as, list only postgres and service_role. A new table created
 *   by a migration no longer grants itself to anon. A new function still did,
 *   through PUBLIC: a per-schema default cannot remove the built-in global
 *   EXECUTE that PUBLIC gets, and anon is a member of PUBLIC. 20260929112318
 *   revokes that globally for postgres.
 *
 *   Two things that closure does not cover. It cannot stop a later migration
 *   writing an explicit GRANT. And the `supabase_admin` grantor still carries
 *   Supabase's original defaults, which do include anon, so an object created by
 *   that role rather than by a migration would still pick anon up. Those are the
 *   residual paths this file is here to catch.
 *
 * HOW TO UPDATE IT, DELIBERATELY
 *   1. Do not edit this file to make a failing check pass. A failure means the
 *      live database changed. Find out which migration changed it first.
 *   2. If the new reach is genuinely wanted, add the entry with a `why` that says
 *      which feature needs it and which migration granted it, in the same pull
 *      request as that migration. Given the note above, wanting it is unlikely.
 *   3. If the new reach is not wanted, write a migration that revokes it. The
 *      shape that actually closes it revokes both together, because
 *      `create function` grants PUBLIC its own EXECUTE and anon is a member of
 *      PUBLIC: `revoke execute on function ... from public, anon;`
 *   4. Re-run `npm run check:anon-access` with SUPABASE_DB_URL set and paste the
 *      result into the pull request.
 *
 * EVIDENCE
 *   Read from project ihyazjaklyhacxixhwww on 5 September 2026, read-only.
 *   Nothing was granted, revoked or migrated to produce it.
 */

