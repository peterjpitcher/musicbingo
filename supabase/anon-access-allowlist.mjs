/**
 * The catalogue query the check runs against the live database. Read-only.
 *
 * It asks `has_*_privilege` rather than reading ACL arrays, because that is the
 * question worth answering: what anon can actually do, including anything it
 * inherits through PUBLIC. Functions are keyed by identity arguments so an
 * overload cannot hide behind a sibling with the same name.
 */
export const ANON_CATALOGUE_QUERY = `
with table_privs as (
  select case when current_setting('server_version_num')::int >= 170000
              then array[${TABLE_PRIVILEGES_PG17.map((p) => `'${p}'`).join(',')}]
              else array[${TABLE_PRIVILEGES.map((p) => `'${p}'`).join(',')}] end as names
),
rel as (
  select case c.relkind when 'r' then 'table' when 'p' then 'table'
                        when 'v' then 'view' when 'm' then 'materialized view' end as kind,
         -- Cast to text: relname uses the Postgres name type, capped at 63
         -- bytes, and a UNION ALL takes its column type from the first branch.
         -- Without this the function signatures below are truncated, so two
         -- overloads that differ only after character 63 collapse into one key
         -- and drift in either of them goes unnoticed.
         c.relname::text as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from table_privs, unnest(table_privs.names) p
           where has_table_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r','p','v','m')
),
seq as (
  select 'sequence' as kind, c.relname::text as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from unnest(array[${SEQUENCE_PRIVILEGES.map((p) => `'${p}'`).join(',')}]) p
           where has_sequence_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'S'
),
fn as (
  select 'function' as kind,
         (p.proname::text || '(' || pg_get_function_identity_arguments(p.oid) || ')')::text as name,
         array['EXECUTE'] as privileges
    from pg_proc p
   where p.pronamespace = 'public'::regnamespace
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
     and has_function_privilege('anon', p.oid, 'EXECUTE')
),
ext_fn as (
  -- Functions an extension owns are reported under their own kind so that
  -- installing, say, pgcrypto into public reads as a separate decision rather
  -- than burying a real regression under forty allowlist entries. They still
  -- fail the check until somebody records them.
  select 'extension function' as kind,
         (p.proname::text || '(' || pg_get_function_identity_arguments(p.oid) || ')')::text as name,
         array['EXECUTE'] as privileges
    from pg_proc p
   where p.pronamespace = 'public'::regnamespace
     and exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
     and has_function_privilege('anon', p.oid, 'EXECUTE')
)
select coalesce(json_agg(row_to_json(x) order by x.kind, x.name), '[]'::json) as reachable
  from (
    select * from rel where cardinality(privileges) > 0
    union all select * from seq where cardinality(privileges) > 0
    union all select * from fn
    union all select * from ext_fn
  ) x;
`.trim();

/**
 * @typedef {object} AnonAccessFinding
 * @property {AnonObjectKind} kind
 * @property {string} name
 * @property {'unlisted' | 'widened'} problem `unlisted` is an object anon can
 *   reach that the allowlist does not mention. `widened` is a listed object
 *   holding privileges beyond those allowed.
 * @property {string[]} extraPrivileges
 * @property {string} [forbidden] Set when a FORBIDDEN_IN_ALLOWLIST rule covers
 *   this reach, which makes it an incident rather than ordinary drift.
 */

/**
 * @typedef {object} AnonAccessDiff
 * @property {AnonAccessFinding[]} findings
 * @property {string[]} stale Allowlisted objects the live database no longer
 *   grants, or grants less of. Not a failure: the world got tighter. Reported so
 *   the file can be trimmed.
 */

const keyOf = (kind, name) => `${kind} ${name}`;

const bareName = (name) => name.split('(')[0];

/**
 * The forbidden rule that covers this reach, or undefined.
 *
 * @param {readonly ForbiddenRule[]} rules
 * @param {AnonObjectKind} kind
 * @param {string} name
 * @param {readonly string[]} privileges
 */
function forbiddenReason(rules, kind, name, privileges) {
  for (const rule of rules) {
    if (rule.kind !== kind) continue;
    if (bareName(rule.name) !== bareName(name)) continue;
    if (rule.privileges === null) return rule.why;
    if (privileges.some((p) => rule.privileges.includes(p))) return rule.why;
  }
  return undefined;
}

/**
 * Compare a live catalogue reading against the allowlist. Pure, so the rules can
 * be exercised without a database. `--self-test` does exactly that.
 *
 * @param {readonly AnonCatalogueEntry[]} reachable
 * @param {readonly AnonAllowlistEntry[]} [allowlist]
 * @param {readonly ForbiddenRule[]} [forbidden]
 * @returns {AnonAccessDiff}
 */
export function diffAnonAccess(
  reachable,
  allowlist = ANON_ALLOWLIST,
  forbidden = FORBIDDEN_IN_ALLOWLIST,
) {
  const allowed = new Map(allowlist.map((entry) => [keyOf(entry.kind, entry.name), entry]));

  /** @type {AnonAccessFinding[]} */
  const findings = [];
  const seen = new Set();

  for (const entry of reachable) {
    const key = keyOf(entry.kind, entry.name);
    seen.add(key);
    const allowedEntry = allowed.get(key);

    if (!allowedEntry) {
      const why = forbiddenReason(forbidden, entry.kind, entry.name, entry.privileges);
      findings.push({
        kind: entry.kind,
        name: entry.name,
        problem: 'unlisted',
        extraPrivileges: [...entry.privileges].sort(),
        ...(why ? { forbidden: why } : {}),
      });
      continue;
    }

    const permitted = new Set(allowedEntry.privileges);
    const extra = entry.privileges.filter((p) => !permitted.has(p)).sort();
    if (extra.length > 0) {
      const why = forbiddenReason(forbidden, entry.kind, entry.name, extra);
      findings.push({
        kind: entry.kind,
        name: entry.name,
        problem: 'widened',
        extraPrivileges: extra,
        ...(why ? { forbidden: why } : {}),
      });
    }
  }

  const stale = [...allowed.keys()].filter((key) => !seen.has(key)).sort();

  return { findings, stale };
}

/**
 * Check the allowlist against its own rules. Needs no database, so it runs on
 * every invocation and an edit that blesses a forbidden object fails offline.
 *
 * @param {readonly AnonAllowlistEntry[]} [allowlist]
 * @param {readonly ForbiddenRule[]} [forbidden]
 * @returns {string[]} One message per problem. Empty means the file is sound.
 */
export function validateAllowlist(
  allowlist = ANON_ALLOWLIST,
  forbidden = FORBIDDEN_IN_ALLOWLIST,
) {
  const problems = [];

  for (const entry of allowlist) {
    if (!entry.why || entry.why.trim().length === 0) {
      problems.push(`${entry.kind} ${entry.name} is allowlisted with no reason recorded.`);
    }
    if (!entry.privileges || entry.privileges.length === 0) {
      problems.push(
        `${entry.kind} ${entry.name} is allowlisted with no privileges, so the entry should be removed.`,
      );
      continue;
    }
    const why = forbiddenReason(forbidden, entry.kind, entry.name, entry.privileges);
    if (why) {
      problems.push(
        `${entry.kind} ${entry.name} must never be allowlisted for anon: ${why}\n` +
          '    If the live database grants it, write a migration that revokes it from PUBLIC and anon. Do not record it here.',
      );
    }
  }

  const seen = new Set();
  for (const entry of allowlist) {
    const key = keyOf(entry.kind, entry.name);
    if (seen.has(key)) problems.push(`${key} is listed twice.`);
    seen.add(key);
  }

  return problems;
}

/**
 * A failure message that names the objects and says what to do about them.
 *
 * @param {readonly AnonAccessFinding[]} findings
 */
export function describeAnonAccessFindings(findings) {
  const lines = [
    `anon can reach ${findings.length} object(s) that supabase/anon-access-allowlist.mjs does not allow.`,
    '',
  ];

  for (const finding of findings) {
    if (finding.problem === 'unlisted') {
      lines.push(
        `  NOT ALLOWLISTED  ${finding.kind} ${finding.name}`,
        `                   anon holds: ${finding.extraPrivileges.join(', ')}`,
      );
    } else {
      lines.push(
        `  WIDENED          ${finding.kind} ${finding.name}`,
        `                   anon gained: ${finding.extraPrivileges.join(', ')}`,
      );
    }
    if (finding.forbidden) {
      lines.push(
        '                   THIS ONE IS AN INCIDENT, NOT ORDINARY DRIFT:',
        `                   ${finding.forbidden}`,
      );
    }
    lines.push('');
  }

  lines.push(
    'Do not edit the allowlist to make this pass. Find the migration that changed',
    'the database. If the reach is wanted, add it to the allowlist with a reason in',
    'the same pull request. If it is not, write a migration that revokes it, from',
    'PUBLIC and anon together, because create function grants PUBLIC its own EXECUTE',
    'and anon is a member of PUBLIC.',
  );

  return lines.join('\n');
}
